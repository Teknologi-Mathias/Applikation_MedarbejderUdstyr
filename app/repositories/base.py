"""Grænseflader for datalagringen.

Services kender kun disse grænseflader – ikke JSON-filer eller databaser.
Implementeringer: app/repositories/supabase/ (standard) og
app/repositories/json/ (kun INBASE_BACKEND=json). app/bootstrap.py vælger.

Fælles regler for alle implementeringer:
- Hver sag har et versionsnummer. gem() afviser med KonfliktFejl, hvis den
  gemte version ikke er den samme, som sagen blev hentet med (optimistisk
  låsning), og tæller versionen op ved succes.
- gem() skriver kun den ene sag (og dens egne opgaver, rykkere og tidslinje).
- Fejl meldes som DataFejl/KonfliktFejl/OfflineFejl (app/repositories/fejl.py).
"""
from typing import Optional, Protocol

from app.domain.sag import Sag


class SagRepository(Protocol):
    proces: str

    def hent_aktive(self) -> list[Sag]: ...
    def hent_arkiverede(self) -> list[Sag]: ...
    def hent(self, sag_id: str) -> Optional[Sag]: ...
    def gem(self, sag: Sag) -> Sag: ...
    def arkiver(self, sag: Sag) -> Sag: ...
    def aktiver(self, sag: Sag) -> Sag: ...
    def slet(self, sag: Sag) -> None: ...
    def signatur(self) -> tuple:
        """(aktive, arkiv): ændrer sig, når listen ændres. Hovedvinduet henter kun den
        halvdel, der er ændret."""


class SkabelonRepository(Protocol):
    def hent_alle(self) -> dict: ...
    def hent(self, slags: str) -> list[dict]:
        """Én slags skabeloner – arbejdsgange uden deres gamle versioner (se versioner())."""

    def versioner(self, skabelon_id: str) -> list[dict]:
        """En arbejdsgangs gemte tidligere udgaver, ældste først."""

    def gem(self, slags: str, skabelon: dict, placering: int) -> None:
        """Opretter/opdaterer ÉN skabelon. placering = dens nummer i listen."""

    def slet(self, slags: str, skabelon_id: str) -> None:
        """Sletter ÉN skabelon. Sager har egne kopier af opgaverne og påvirkes ikke."""


class BrugerRepository(Protocol):
    """Lokale konti (kun JSON-tilstanden)."""

    def hent_alle(self) -> list[dict]: ...
    def gem_alle(self, brugere: list[dict]) -> None: ...


class KontoRepository(Protocol):
    """Konti hos en ekstern identitetsudbyder (Supabase Auth + profiler).

    Brugernavne er normaliserede (app/domain/bruger.py). Hvordan et brugernavn
    bliver til en login-identifikator hos udbyderen, er repositoryets sag.
    """

    def log_ind(self, brugernavn: str, kode: str) -> str:
        """Brugerens id. Kaster ForkertLoginFejl ved forkert brugernavn/kode."""
    def log_ud(self) -> None: ...
    def profil(self, bruger_id: str) -> Optional[dict]:
        """Profilen (også en deaktiveret), None hvis ingen. SessionUdloebetFejl ved udløbet session."""
    def alle_profiler(self) -> list[dict]: ...
    def katalog(self) -> list[dict]: ...
    def skift_egen_kode(self, ny_kode: str) -> None: ...
    def opret(self, brugernavn: str, navn: str, rolle: str, kode: str) -> dict: ...
    def nulstil_kode(self, bruger_id: str, kode: str) -> None: ...
    def saet_aktiv(self, bruger_id: str, aktiv: bool) -> None: ...
    def saet_rolle(self, bruger_id: str, rolle: str) -> None: ...
    def saet_moduler(self, bruger_id: str, moduler: list[str]) -> None: ...
    def saet_afdelinger(self, bruger_id: str, afdelinger: list[str]) -> None: ...
    def saet_opdateringskanal(self, bruger_id: str, kanal: str) -> None: ...
    def slet(self, bruger_id: str) -> None: ...


class IndmeldingRepository(Protocol):
    """Ønsker & Udvikling: indmeldinger, kommentarer og ændringshistorik.

    Indsender og forfatter bestemmes af lagringen ud fra den, der er logget
    på – aldrig af et id fra klienten. opdater() afviser med KonfliktFejl,
    hvis versionen ikke er den, indmeldingen blev hentet med.
    """

    def hent_alle(self) -> list: ...
    def hent(self, indmelding_id: str): ...
    def opret(self, felter: dict): ...
    def opdater(self, indmelding_id: str, version: int, aendringer: dict): ...
    def slet(self, indmelding_id: str) -> None: ...
    def kommentarer(self, indmelding_id: str) -> list: ...
    def tilfoej_kommentar(self, indmelding_id: str, tekst: str, intern: bool): ...
    def historik(self, indmelding_id: str) -> list: ...
    def signatur(self) -> tuple: ...


class MdmRepository(Protocol):
    """Telefoner (MDM): én række pr. telefon (migrering 007).

    opdater() tager en liste af {"id": ..., felt: værdi} og gemmer dem i ét
    kald (sparer trafik ved synkronisering). Returnerer antal ændrede rækker.
    hent() henter én telefon (Find telefon venter på svaret uden at hente hele listen).
    app_info()/udgiv_app(): styrings-appen, som telefonerne selv henter (migrering 026).
    """

    def hent_alle(self) -> list: ...
    def hent(self, enhed_id: str): ...
    def opret(self, enhed): ...
    def opdater(self, aendringer: list[dict]) -> int: ...
    def slet(self, enhed_id: str) -> None: ...
    def app_info(self) -> dict: ...
    def udgiv_app(self, version_code: int, version_name: str, apk: bytes) -> dict: ...


class OpdateringRepository(Protocol):
    """Central opdatering (migrering 019): krav til klienten og udgivne versioner.

    udgivelser() returnerer kun de versioner, brugeren må se (RLS: stabil for
    alle, pilot kun for brugere med pilotkanal).
    """

    def krav(self) -> dict: ...
    def udgivelser(self) -> list: ...
    def rapporter(self, version: str) -> None: ...
    def download_url(self, sti: str) -> str: ...


class KalenderRepository(Protocol):
    """Kalender (migrering 020–022): kalendere og begivenheder.

    Ejer og opretter bestemmes af lagringen ud fra login. kalendre() giver alle
    kalendere (egne og kollegers – Kalender.adgang). begivenheder() giver de
    begivenheder (serier og rettede forekomster), der kan have forekomster i
    tidsrummet – private i andres kalendere maskeret ("Optaget"); udfoldningen
    sker i domænet. opdater()/opdater_kalender() afviser med KonfliktFejl, hvis
    versionen ikke er den, der blev hentet. importer() springer dubletter over og
    returnerer antal oprettede.
    """

    def kalendre(self) -> list: ...
    def opret_kalender(self, kalender): ...
    def opdater_kalender(self, kalender_id: str, version: int, aendringer: dict): ...
    def slet_kalender(self, kalender_id: str) -> None: ...
    def begivenheder(self, fra, til) -> list: ...
    def opret(self, begivenhed): ...
    def opdater(self, begivenhed): ...
    def slet(self, begivenhed_id: str) -> None: ...
    def importer(self, kalender_id: str, begivenheder: list) -> int: ...
    def signatur(self) -> tuple: ...


class IndstillingRepository(Protocol):
    """Fælles indstillinger (backup, slettepolitik, områder, regler)."""

    def hent(self) -> dict: ...
    def gem(self, indstillinger: dict) -> None: ...


class PraeferenceRepository(Protocol):
    """Den enkelte brugers præferencer (tema, notifikationer)."""

    def hent(self, brugernavn: str) -> dict: ...
    def gem(self, brugernavn: str, praeferencer: dict) -> None: ...
